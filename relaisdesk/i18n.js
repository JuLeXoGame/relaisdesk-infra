  const STORAGE_KEY = 'relaisdesk_lang';
  let currentLang = null;

  function getLang() {
    if (currentLang && LANG_CONFIG[currentLang]) return currentLang;
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANG_CONFIG[saved]) {
        currentLang = saved;
        return saved;
      }
    } catch (_) {}
    const nav = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (nav.startsWith('fr')) return 'fr';
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('it')) return 'it';
    if (nav.startsWith('ru')) return 'ru';
    if (nav.startsWith('pl')) return 'pl';
    if (nav.startsWith('en')) return 'en';
    return 'fr';
  }

  function t(key, lang) {
    const l = lang || getLang();
    const dict = translations[l] || translations.fr;
    return dict[key] !== undefined ? dict[key] : (translations.fr[key] !== undefined ? translations.fr[key] : key);
  }

  function closeAllDropdowns() {
    document.querySelectorAll('.lang-selector-dropdown.open').forEach(dropdown => {
      dropdown.classList.remove('open');
      const btn = dropdown.querySelector('.lang-dropdown-btn');
      if (btn) btn.setAttribute('aria-expanded', 'false');
    });
  }

  function updateDropdownUI(lang) {
    const config = LANG_CONFIG[lang] || LANG_CONFIG.fr;

    // Update all dropdown triggers on page
    document.querySelectorAll('.lang-selector-dropdown').forEach(dropdown => {
      const flagEl = dropdown.querySelector('.lang-btn-flag');
      const codeEl = dropdown.querySelector('.lang-btn-code');
      const btn = dropdown.querySelector('.lang-dropdown-btn');

      if (flagEl) flagEl.textContent = config.flag;
      if (codeEl) codeEl.textContent = config.code;
      if (btn) btn.setAttribute('aria-label', `Langue: ${config.name}`);

      // Update active state in list
      dropdown.querySelectorAll('.lang-dropdown-item').forEach(item => {
        const itemLang = item.getAttribute('data-lang');
        const check = item.querySelector('.lang-check');
        if (itemLang === lang) {
          item.classList.add('active');
          item.setAttribute('aria-selected', 'true');
          if (check) check.textContent = '✓';
        } else {
          item.classList.remove('active');
          item.setAttribute('aria-selected', 'false');
          if (check) check.textContent = '';
        }
      });
    });

    // Fallback for any legacy toggle buttons
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      btn.textContent = `${config.flag} ${config.code}`;
      btn.setAttribute('aria-label', `Langue: ${config.name}`);
    });
  }

  function setLanguage(lang) {
    if (!LANG_CONFIG[lang]) lang = 'fr';
    currentLang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (_) {}
    document.documentElement.lang = lang;

    // Translate elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const val = t(key, lang);
      if (val !== undefined) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.hasAttribute('placeholder')) el.placeholder = val;
        } else {
          el.textContent = val;
        }
      }
    });

    // Translate elements with data-i18n-html (allows bold or spans)
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      const val = t(key, lang);
      if (val !== undefined) el.innerHTML = val;
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = t(key, lang);
    });

    // Translate titles / tooltips
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      el.title = t(key, lang);
    });

    // Update dropdown UI state
    updateDropdownUI(lang);

    // Dispatch event for dynamic components (pricing, slider, modals)
    window.dispatchEvent(new CustomEvent('relaisdesk:langchange', { detail: { lang } }));
  }

  function initDropdownEvents() {
    // Delegated click listener for dropdowns
    document.addEventListener('click', (e) => {
      const btn = e.target.closest('.lang-dropdown-btn');
      if (btn) {
        e.preventDefault();
        e.stopPropagation();
        const dropdown = btn.closest('.lang-selector-dropdown');
        if (!dropdown) return;
        const isOpen = dropdown.classList.contains('open');
        closeAllDropdowns();
        if (!isOpen) {
          dropdown.classList.add('open');
          btn.setAttribute('aria-expanded', 'true');
        }
        return;
      }

      const item = e.target.closest('.lang-dropdown-item');
      if (item) {
        e.preventDefault();
        e.stopPropagation();
        const selectedLang = item.getAttribute('data-lang');
        if (selectedLang && LANG_CONFIG[selectedLang]) {
          setLanguage(selectedLang);
        }
        closeAllDropdowns();
        return;
      }

      // Click outside
      if (!e.target.closest('.lang-selector-dropdown')) {
        closeAllDropdowns();
      }
    });

    // Keyboard support: Escape closes dropdown
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') {
        closeAllDropdowns();
      }
    });

    // Legacy toggle buttons support
    document.querySelectorAll('.lang-toggle-btn').forEach((btn) => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const current = getLang();
        const langs = Object.keys(LANG_CONFIG);
        const nextIdx = (langs.indexOf(current) + 1) % langs.length;
        setLanguage(langs[nextIdx]);
      });
    });
  }

  function init() {
    const current = getLang();
    setLanguage(current);
    initDropdownEvents();
  }

  window.RdI18n = {
    t,
    getLang,
    setLanguage,
    init,
    translations,
    LANG_CONFIG
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
